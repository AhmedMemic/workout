import type { Equipment, Exercise, ExerciseKind, Muscle } from './types'

interface Opts {
  measure?: 'reps' | 'time'
  perSide?: boolean
  youtube?: string
}

function ex(
  id: string,
  en: string,
  bs: string,
  kind: ExerciseKind,
  muscles: Muscle[],
  equipment: Equipment[],
  stepsEn: string[],
  stepsBs: string[],
  opts: Opts = {},
): Exercise {
  return {
    id,
    name: { en, bs },
    kind,
    muscles,
    equipment,
    steps: { en: stepsEn, bs: stepsBs },
    measure: opts.measure ?? 'reps',
    perSide: opts.perSide,
    youtube: opts.youtube ?? `how to ${en.toLowerCase()} proper form`,
  }
}

