export function getExercise(id: string): Exercise {
  const e = exerciseById[id]
  if (!e) throw new Error(`Unknown exercise: ${id}`)
  return e
}

export function youtubeUrl(e: Exercise): string {
  return `https://www.youtube.com/results?search_query=${encodeURIComponent(e.youtube)}`
}
